#!/usr/bin/env python3
"""Embed the files under web/ into a C source file.

Usage: embed_web.py <web_dir> <output.c>

Generates `const wp_asset wp_assets[]` (see src/server.c), terminated by an
entry with a NULL path. Paths are URL paths relative to the web root, e.g.
"/index.html", "/js/app.js".
"""
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".txt": "text/plain; charset=utf-8",
}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root, out = sys.argv[1], sys.argv[2]
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for name in sorted(filenames):
            if name.startswith("."):
                continue
            full = os.path.join(dirpath, name)
            rel = "/" + os.path.relpath(full, root).replace(os.sep, "/")
            files.append((rel, full))

    lines = [
        "/* Generated by tools/embed_web.py - do not edit. */",
        "#include <stddef.h>",
        "",
        "typedef struct { const char *path; const char *mime; "
        "const unsigned char *data; size_t len; } wp_asset;",
        "",
    ]
    for i, (rel, full) in enumerate(files):
        with open(full, "rb") as f:
            data = f.read()
        lines.append(f"/* {rel} */")
        lines.append(f"static const unsigned char asset_{i}[] = {{")
        for off in range(0, len(data), 20):
            chunk = data[off:off + 20]
            lines.append("    " + ",".join(str(b) for b in chunk) + ",")
        lines.append("    0")
        lines.append("};")
    lines.append("")
    lines.append("const wp_asset wp_assets[] = {")
    for i, (rel, full) in enumerate(files):
        ext = os.path.splitext(rel)[1].lower()
        mime = MIME.get(ext, "application/octet-stream")
        size = os.path.getsize(full)
        lines.append(f'    {{ "{rel}", "{mime}", asset_{i}, {size} }},')
    lines.append("    { NULL, NULL, NULL, 0 },")
    lines.append("};")
    lines.append("")

    tmp = out + ".tmp"
    with open(tmp, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    os.replace(tmp, out)


if __name__ == "__main__":
    main()
